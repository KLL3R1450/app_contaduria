    private void cargarClientesYRegimenes(){
        modeloRegimenesD.removeAllElements();
        modeloClientesD.removeAllElements();
        
        for(Regimenes o : c.getRegimenes()){
            allRegimenes.add(o);
            modeloRegimenesD.addElement(o.regimen);
        }
        
        for(Cliente cli : c.getAllClientes().values()){
            allClientes.add(cli);
            modeloClientesD.addElement(cli.nombre);
        }
        
        
    }
    
