    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        if(TNom.getText().isEmpty() || TCp.getText().isEmpty() ||
            TRfc.getText().isEmpty()){
            JOptionPane.showMessageDialog(rootPane, "Valores no validos");
            return;
        }

        if(TNom.getText().isEmpty()){
            JOptionPane.showMessageDialog(rootPane, "Nombre no valido");
            return;
        }

        if(!Validator.validarCorreo(TCorr.getText()) && !TCorr.getText().isEmpty()){
            JOptionPane.showMessageDialog(rootPane, "Correo no valido");
            return;
        }

        if(!Validator.validarCodigoPostal(TCp.getText())){
            JOptionPane.showMessageDialog(rootPane, "Codigo Postal no valido");
            return;
        }

        if(!Validator.validarRFC(TRfc.getText())){
            JOptionPane.showMessageDialog(rootPane, "RFC no valido");
            return;
        }

        ArrayList<Integer> idReg = new ArrayList<>();
        ArrayList<Integer> idClientes = new ArrayList<>();

        for(Object regimen : listaRegimenesA) idReg.add(((Regimenes)regimen).getId());

        for(Object cliente : listaClientesA) idClientes.add(((Cliente)cliente).id_persona);
        
        Terceros tercero = new Terceros(
            TNom.getText(),
            TRfc.getText(),
            TCp.getText(),
            TCorr.getText());

        tercero.idsRegimenes = idReg;

        String respuesta = c.insertTercero(tercero, idClientes);

        if(!"correcto".equals(respuesta)) {
            JOptionPane.showMessageDialog(rootPane, respuesta);
            return;
        }

        borrarValores();
        JOptionPane.showMessageDialog(rootPane, "Tercero insertado con exito");
    }//GEN-LAST:event_jButton1ActionPerformed

